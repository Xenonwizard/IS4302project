/**
 * Copies what the Next.js app needs from a finished Ignition deployment into
 * src/lib/chain/generated.ts: each contract's ABI (as const, so viem/wagmi infer argument and
 * return types from it) and its address per chain id, plus the block the deploy started at
 * so event queries don't scan the chain from genesis.
 *
 *   node scripts/export-frontend.mjs 31337   # after deploy:local
 *   node scripts/export-frontend.mjs 80002   # after deploy:amoy
 *
 * Addresses for every chain already exported are kept, so local and Amoy can live side by side.
 */
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const chainId = process.argv[2];
if (!chainId) throw new Error("usage: node scripts/export-frontend.mjs <chainId>");

const dir = join(root, "ignition", "deployments", `chain-${chainId}`);
const MODULE = "PokechainModule";
const CONTRACTS = ["MockUSDC", "AccountRegistry", "SlabVault", "TradeEscrow", "SlabMarket", "LostSlabRecovery"];

const addresses = JSON.parse(readFileSync(join(dir, "deployed_addresses.json"), "utf8"));
const blocks = readFileSync(join(dir, "journal.jsonl"), "utf8")
  .split("\n")
  .flatMap((line) => [...line.matchAll(/"blockNumber":(\d+)/g)].map((m) => Number(m[1])));
const fromBlock = blocks.length ? Math.min(...blocks) : 0;

const abis = Object.fromEntries(
  CONTRACTS.map((name) => [name, JSON.parse(readFileSync(join(dir, "artifacts", `${MODULE}#${name}.json`), "utf8")).abi]),
);

const out = join(root, "..", "src", "lib", "chain", "generated.ts");
let deployments = {};
if (existsSync(out)) {
  const m = readFileSync(out, "utf8").match(/export const deployments = (\{[\s\S]*?\n\}) as const;/);
  if (m) deployments = JSON.parse(m[1]);
}
deployments[chainId] = {
  ...Object.fromEntries(CONTRACTS.map((name) => [name, addresses[`${MODULE}#${name}`]])),
  fromBlock,
};

const body = [
  "// Generated by blockchain/scripts/export-frontend.mjs after each deploy. Do not edit by hand.",
  "",
  `export const deployments = ${JSON.stringify(deployments, null, 2)} as const;`,
  "",
  ...CONTRACTS.map((name) => `export const ${name[0].toLowerCase()}${name.slice(1)}Abi = ${JSON.stringify(abis[name], null, 2)} as const;\n`),
].join("\n");

writeFileSync(out, body);
console.log(`Wrote ${CONTRACTS.join(", ")} for chain ${chainId} to src/lib/chain/generated.ts (from block ${fromBlock})`);
