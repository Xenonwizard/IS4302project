export function syntheticHandle(rnd: () => number): string {
  const a = ADJ[Math.floor(rnd() * ADJ.length)];
  const n = NOUN[Math.floor(rnd() * NOUN.length)];
  const num = Math.floor(rnd() * 10999) + 1000;
  return `${a}${n}${num}`;
}

